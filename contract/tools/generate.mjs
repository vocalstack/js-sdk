#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const contractPath = process.argv[2] ?? path.join(here, '..', 'contract.json');
const outDir = process.argv[3] ?? path.join(here, '..', 'src');

const doc = JSON.parse(fs.readFileSync(contractPath, 'utf8'));
const openapi = doc.openapi;
const schemas = openapi.components.schemas;


const literalUnionValues = (schema) => {
  if (!Array.isArray(schema.oneOf)) return null;
  const values = [];
  for (const v of schema.oneOf) {
    if (v.const !== undefined) values.push(v.const);
    else if (Array.isArray(v.enum)) values.push(...v.enum);
    else return null;
  }
  return values.length ? values : null;
};

const refName = (ref) => {
  const m = /^#\/components\/schemas\/([A-Za-z0-9_]+)$/.exec(ref);
  if (!m) throw new Error(`unsupported $ref: ${ref}`);
  return m[1];
};

const zid = (name) => `${name}Schema`;

function zodFor(schema, ctx) {
  if (schema.$ref) {
    ctx.deps.add(refName(schema.$ref));
    return zid(refName(schema.$ref));
  }
  const literals = literalUnionValues(schema);
  if (literals) {
    const lits = literals.map((v) => `z.literal(${JSON.stringify(v)})`);
    // z.union needs two members: a one-value union is its literal.
    return lits.length > 1 ? `z.union([${lits.join(', ')}])` : lits[0];
  }
  if (Array.isArray(schema.anyOf)) {
    const parts = schema.anyOf.map((v) => zodFor(v, ctx));
    return parts.length > 1 ? `z.union([${parts.join(', ')}])` : parts[0];
  }
  if (schema.oneOf) {
    const tags = schema.oneOf.map((v) => discriminatorOf(v));
    const tag = tags.every((t) => t && t === tags[0]) ? tags[0] : null;
    const variants = schema.oneOf.map((v) => zodFor(v, ctx)).join(', ');
    return tag
      ? `z.discriminatedUnion('${tag}', [${variants}])`
      : `z.union([${variants}])`;
  }
  if (schema.enum) {
    if (!schema.enum.every((v) => typeof v === 'string'))
      throw new Error(`non-string enum: ${JSON.stringify(schema.enum)}`);
    return `z.enum([${schema.enum.map((v) => `'${v}'`).join(', ')}])`;
  }
  if (schema.const !== undefined) {
    return `z.literal(${JSON.stringify(schema.const)})`;
  }
  const types = Array.isArray(schema.type) ? schema.type : [schema.type];
  if (types.length > 1) {
    const parts = types.map((t) => zodFor({ ...schema, type: t }, ctx));
    return `z.union([${parts.join(', ')}])`;
  }
  switch (types[0]) {
    case 'null':
      return 'z.null()';
    case 'boolean':
      return 'z.boolean()';
    case 'integer':
      return 'z.number().int()';
    case 'number':
      return 'z.number()';
    case 'string':
      return 'z.string()';
    case 'array':
      return `z.array(${zodFor(schema.items ?? {}, ctx)})`;
    case 'object': {
      const props = schema.properties ?? {};
      const required = new Set(schema.required ?? []);
      if (!Object.keys(props).length && schema.additionalProperties) {
        return `z.record(z.string(), ${zodFor(schema.additionalProperties, ctx)})`;
      }
      const fields = Object.entries(props)
        .map(([k, v]) => {
          let expr = zodFor(v, ctx);
          if (!required.has(k)) expr += '.optional()';
          return `  ${JSON.stringify(k)}: ${expr},`;
        })
        .join('\n');
      return `z.object({\n${fields}\n})`;
    }
    case undefined:
      return 'z.unknown()';
    default:
      throw new Error(`unsupported schema: ${JSON.stringify(schema)}`);
  }
}

function discriminatorOf(variant) {
  if (variant.type !== 'object' || !variant.properties) return null;
  for (const [k, v] of Object.entries(variant.properties)) {
    if (v.const !== undefined && (variant.required ?? []).includes(k)) return k;
  }
  return null;
}


const nodes = new Map();
for (const [name, schema] of Object.entries(schemas)) {
  const ctx = { deps: new Set() };
  const code = zodFor(schema, ctx);
  nodes.set(name, { code, deps: ctx.deps });
}

const ordered = [];
const seen = new Set();
const visiting = new Set();
function visit(name) {
  if (seen.has(name)) return;
  if (visiting.has(name)) throw new Error(`schema cycle at ${name}`);
  visiting.add(name);
  for (const d of nodes.get(name).deps) visit(d);
  visiting.delete(name);
  seen.add(name);
  ordered.push(name);
}
for (const name of nodes.keys()) visit(name);

const header = `// GENERATED by tools/generate.mjs from contract.json — do not edit.\n`;

let schemasTs = `${header}import { z } from 'zod';\n\n`;
for (const name of ordered) {
  schemasTs += `export const ${zid(name)} = ${nodes.get(name).code};\n`;
  schemasTs += `export type ${name} = z.infer<typeof ${zid(name)}>;\n\n`;
}



const framesTs = `${header}import * as s from './schemas.js';
import type { ServerFrame } from './schemas.js';

/** Known server frame \`type\` values (unknown types MUST be ignored). */
export const SERVER_FRAME_TYPES = ${JSON.stringify(
  (schemas.ServerFrame.oneOf ?? []).map((v) => v.properties.type.const),
  null,
  2,
)} as const;

/**
 * Parse one WS text frame. Returns null for frames of unknown type
 * (forward compatibility) — throws only on malformed known frames.
 */
export function parseServerFrame(text: string): ServerFrame | null {
  const raw = JSON.parse(text) as { type?: string };
  if (!raw || typeof raw.type !== 'string') return null;
  if (!(SERVER_FRAME_TYPES as readonly string[]).includes(raw.type)) return null;
  return s.ServerFrameSchema.parse(raw);
}
`;

const indexTs = `${header}export * from './schemas.js';
export * from './frames.js';
`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'schemas.ts'), schemasTs);
// No client contract here: the SDK is the one client (deviation 73).
fs.rmSync(path.join(outDir, 'contract.ts'), { force: true });
fs.writeFileSync(path.join(outDir, 'frames.ts'), framesTs);
fs.writeFileSync(path.join(outDir, 'index.ts'), indexTs);
console.log(`generated ${ordered.length} schemas → ${outDir}`);


const pyFlag = process.argv.indexOf('--python');
if (pyFlag !== -1) {
  const pyOut =
    process.argv[pyFlag + 1] ??
    path.join(here, '..', '..', '..', 'sdks', 'python', 'src', 'vocalstack', '_models.py');
  fs.writeFileSync(pyOut, emitPython());
  console.log(`generated pydantic models → ${pyOut}`);
}

function emitPython() {
  const PY_KEYWORDS = new Set([
    'False', 'None', 'True', 'and', 'as', 'assert', 'async', 'await', 'break', 'class', 'continue', 'def', 'del', 'elif', 'else',
    'except', 'finally', 'for', 'from', 'global', 'if', 'import', 'in', 'is', 'lambda', 'nonlocal', 'not', 'or', 'pass', 'raise',
    'return', 'try', 'while', 'with', 'yield',
  ]);
  const snake = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
  const classFromTag = (tag) => {
    const name = tag
      .split(/[._]/)
      .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
      .join('');
    return name === 'Error' ? 'ErrorFrame' : name;
  };

  const aliases = new Map();
  const classes = [];
  const unions = [];
  // A schema that is only a `$ref` (Broadcast, Transcription: another
  // name for Session) is bound after the class it names exists.
  const refAliases = [];

  for (const name of ordered) {
    const schema = schemas[name];
    const literalValues = literalUnionValues(schema);
    if (schema.$ref && !aliases.has(refName(schema.$ref))) {
      refAliases.push([name, refName(schema.$ref), schema.description]);
    } else if (literalValues) {
      aliases.set(name, `Literal[${literalValues.map((v) => JSON.stringify(v)).join(', ')}]`);
    } else if (schema.oneOf) {
      unions.push([name, schema.oneOf]);
    } else if (schema.enum || schema.const !== undefined) {
      const values = schema.enum ?? [schema.const];
      aliases.set(name, `Literal[${values.map((v) => JSON.stringify(v)).join(', ')}]`);
    } else if ((Array.isArray(schema.type) ? schema.type[0] : schema.type) === 'object') {
      classes.push([name, schema]);
    } else {
      aliases.set(name, pyType(schema));
    }
  }

  function pyType(schema) {
    if (schema.$ref) {
      const n = refName(schema.$ref);
      return aliases.has(n) ? n : `"${n}"`;
    }
    // An untyped schema (serde_json::Value) is free-form JSON.
    if (
      schema.type === undefined && schema.$ref === undefined && schema.anyOf === undefined &&
      schema.allOf === undefined && schema.oneOf === undefined && schema.enum === undefined &&
      schema.const === undefined
    ) {
      return 'Any';
    }
    const inlineLiterals = literalUnionValues(schema);
    if (inlineLiterals)
      return `Literal[${inlineLiterals.map((v) => JSON.stringify(v)).join(', ')}]`;
    if (schema.enum) return `Literal[${schema.enum.map((v) => JSON.stringify(v)).join(', ')}]`;
    if (schema.const !== undefined) return `Literal[${JSON.stringify(schema.const)}]`;
    if (Array.isArray(schema.anyOf)) {
      const variants = schema.anyOf.filter((v) => v.type !== 'null');
      const inner = variants.map((v) => pyType(v));
      const u = inner.length > 1 ? `Union[${inner.join(', ')}]` : inner[0];
      return variants.length < schema.anyOf.length ? `Optional[${u}]` : u;
    }
    const types = Array.isArray(schema.type) ? schema.type : [schema.type];
    if (types.length > 1) {
      const nonNull = types.filter((t) => t !== 'null');
      const inner = nonNull.map((t) => pyType({ ...schema, type: t }));
      const u = inner.length > 1 ? `Union[${inner.join(', ')}]` : inner[0];
      return types.includes('null') ? `Optional[${u}]` : u;
    }
    switch (types[0]) {
      case 'boolean':
        return 'bool';
      case 'integer':
        return 'int';
      case 'number':
        return 'float';
      case 'string':
        return 'str';
      case 'null':
        return 'None';
      case 'array':
        return `List[${pyType(schema.items ?? {})}]`;
      case 'object':
        if (schema.additionalProperties && !schema.properties) {
          return `Dict[str, ${pyType(schema.additionalProperties)}]`;
        }
        // A map with a non-string key: serde writes the key as a string,
        // and schemars says which strings are allowed with
        // `patternProperties`. Rust's HashMap<i32, f64> arrives here.
        if (schema.patternProperties && !schema.properties) {
          const vals = Object.values(schema.patternProperties);
          if (vals.length === 1) return `Dict[str, ${pyType(vals[0])}]`;
        }
        throw new Error(`unsupported python type: ${JSON.stringify(schema)}`);
      default:
        throw new Error(`unsupported python type: ${JSON.stringify(schema)}`);
    }
  }

  function emitClass(name, schema, indentDoc) {
    const props = schema.properties ?? {};
    const required = new Set(schema.required ?? []);
    let out = `class ${name}(_Base):\n`;
    if (indentDoc) out += `    """${indentDoc}"""\n\n`;
    if (!Object.keys(props).length) {
      out += '    pass\n';
      return out;
    }
    for (const [k, v] of Object.entries(props)) {
      // A Python keyword (`from`) is not a field name: `from_`, aliased.
      const field = PY_KEYWORDS.has(snake(k)) ? `${snake(k)}_` : snake(k);
      let type = pyType(v);
      let line;
      if (v.const !== undefined) {
        line = `    ${field}: ${type} = ${JSON.stringify(v.const)}\n`;
      } else if (required.has(k)) {
        line =
          field === k
            ? `    ${field}: ${type}\n`
            : `    ${field}: ${type} = Field(alias=${JSON.stringify(k)})\n`;
      } else {
        const opt = type.startsWith('Optional[') ? type : `Optional[${type}]`;
        line =
          field === k
            ? `    ${field}: ${opt} = None\n`
            : `    ${field}: ${opt} = Field(default=None, alias=${JSON.stringify(k)})\n`;
      }
      out += line;
    }
    return out;
  }

  let py = `# GENERATED by @vocalstack/contract tools/generate.mjs — do not edit.\n`;
  py += `from __future__ import annotations\n\n`;
  py += `import json\nfrom typing import Any, Dict, List, Literal, Optional, Union\n\n`;
  py += `from pydantic import BaseModel, ConfigDict, Field, TypeAdapter\n\n\n`;
  py += `class _Base(BaseModel):\n`;
  py += `    # extra="ignore": additive contract changes must not break clients.\n`;
  py += `    model_config = ConfigDict(populate_by_name=True, extra="ignore")\n\n\n`;

  for (const [name, expr] of aliases) {
    py += `${name} = ${expr}\n\n`;
  }
  py += '\n';
  for (const [name, schema] of classes) {
    py += emitClass(name, schema, schema.description) + '\n\n';
  }

  const unionMeta = [];
  for (const [name, variants] of unions) {
    const parts = [];
    // The discriminator is whatever const property every variant shares:
    // `type` for frames, `kind` for CaptureSource.  Variant classes of a
    // non-frame union are prefixed with the union's name so `mic` does not
    // become a bare `Mic`.
    const disc = discriminatorOf(variants[0]) ?? 'type';
    for (const v of variants) {
      const tag = v.properties?.[disc]?.const;
      if (tag === undefined) throw new Error(`untagged union variant in ${name}`);
      const cls = disc === 'type' ? classFromTag(tag) : `${name}${classFromTag(tag)}`;
      py += emitClass(cls, v) + '\n\n';
      parts.push({ cls, tag });
    }
    py += `${name} = Annotated[Union[${parts.map((p) => p.cls).join(', ')}], Field(discriminator=${JSON.stringify(disc)})]\n\n`;
    unionMeta.push({ name, parts });
  }

  for (const [name, target, description] of refAliases) {
    if (description) py += `# ${description}\n`;
    py += `${name} = ${target}\n\n`;
  }

  py = py.replace(
    'from typing import Any, Dict, List, Literal, Optional, Union',
    'from typing import Annotated, Any, Dict, List, Literal, Optional, Union',
  );

  const server = unionMeta.find((u) => u.name === 'ServerFrame');
  if (server) {
    py += `SERVER_FRAME_TYPES = frozenset([${server.parts
      .map((p) => JSON.stringify(p.tag))
      .join(', ')}])\n\n`;
    py += `_server_frame_adapter: TypeAdapter[ServerFrame] = TypeAdapter(ServerFrame)\n\n\n`;
    const transcript = server.parts.filter((p) => p.tag.startsWith('transcript.'));
    py += `TranscriptEvent = Union[${transcript.map((p) => p.cls).join(', ')}]\n\n\n`;
    py += `def parse_server_frame(text: str) -> Optional[ServerFrame]:\n`;
    py += `    """Parse one WS text frame. Returns None for unknown frame types\n`;
    py += `    (forward compatibility)."""\n`;
    py += `    raw = json.loads(text)\n`;
    py += `    if not isinstance(raw, dict) or raw.get("type") not in SERVER_FRAME_TYPES:\n`;
    py += `        return None\n`;
    py += `    return _server_frame_adapter.validate_python(raw)\n`;
  }
  return py;
}
